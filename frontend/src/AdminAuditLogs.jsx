import { useCallback, useEffect, useState } from 'react';
import { ChevronLeft, ChevronRight, Download, RefreshCw, ShieldAlert } from 'lucide-react';
import apiClient from './api/axios.js';
import './adminAuditLogs.css';

const initialPagination = { page: 1, pageSize: 20, total: 0 };
const emptyFilters = {
  q: '',
  actor: '',
  action: '',
  module: '',
  entityType: '',
  entityId: '',
  requestId: '',
  severity: '',
  outcome: '',
  dateFrom: '',
  dateTo: '',
};

function errorText(error) {
  return error.response?.data?.error || error.message || 'The request could not be completed.';
}

function formatDate(value) {
  if (!value) return '—';
  const date = new Date(String(value).replace(' ', 'T'));
  return Number.isNaN(date.getTime()) ? String(value) : new Intl.DateTimeFormat(undefined, {
    dateStyle: 'medium',
    timeStyle: 'medium',
  }).format(date);
}

function label(value) {
  return String(value || 'unknown').replaceAll('_', ' ').replaceAll('.', ' · ');
}

export default function AdminAuditLogs() {
  const [rows, setRows] = useState([]);
  const [pagination, setPagination] = useState(initialPagination);
  const [filters, setFilters] = useState(emptyFilters);
  const [options, setOptions] = useState({ actions: [], modules: [], canExport: false });
  const [sortBy, setSortBy] = useState('created_at');
  const [sortDirection, setSortDirection] = useState('desc');
  const [loading, setLoading] = useState(true);
  const [exporting, setExporting] = useState(false);
  const [error, setError] = useState('');

  const load = useCallback(async (page = 1) => {
    setLoading(true);
    setError('');
    try {
      const response = await apiClient.get('/admin/audit-logs', {
        params: {
          page,
          pageSize: pagination.pageSize,
          sortBy,
          sortDirection,
          ...Object.fromEntries(Object.entries(filters).filter(([, value]) => value !== '')),
        },
      });
      setRows(response.data.data || []);
      setPagination(response.data.pagination || initialPagination);
    } catch (issue) {
      setError(errorText(issue));
    } finally {
      setLoading(false);
    }
  }, [filters, pagination.pageSize, sortBy, sortDirection]);

  useEffect(() => { void load(1); }, [load]);

  useEffect(() => {
    let active = true;
    apiClient.get('/admin/audit-logs/options')
      .then((response) => {
        if (active) setOptions(response.data.data || { actions: [], modules: [], canExport: false });
      })
      .catch((issue) => {
        if (active) setError(errorText(issue));
      });
    return () => { active = false; };
  }, []);

  function updateFilter(field, value) {
    setFilters((current) => ({ ...current, [field]: value }));
  }

  async function exportLogs() {
    setExporting(true);
    setError('');
    try {
      const response = await apiClient.get('/admin/audit-logs/export', {
        params: {
          sortBy,
          sortDirection,
          ...Object.fromEntries(Object.entries(filters).filter(([, value]) => value !== '')),
        },
        responseType: 'blob',
      });
      const url = URL.createObjectURL(response.data);
      const link = document.createElement('a');
      link.href = url;
      link.download = 'audit-logs.csv';
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(url);
    } catch (issue) {
      setError(errorText(issue));
    } finally {
      setExporting(false);
    }
  }

  const pageCount = Math.max(1, Math.ceil(pagination.total / pagination.pageSize));

  return (
    <section className="page admin-audit-logs">
      <div className="page-heading admin-audit-heading">
        <div>
          <h1>Audit Logs</h1>
          <p>Read-only history of administrative and security-sensitive changes.</p>
        </div>
        {options.canExport && (
          <button className="button" type="button" disabled={exporting || loading} onClick={exportLogs}>
            <Download size={16}/> {exporting ? 'Preparing export…' : 'Export filtered records'}
          </button>
        )}
      </div>

      <div className="admin-audit-notice">
        <ShieldAlert size={18}/>
        <span>Audit records are generated by the server and cannot be changed or deleted from this screen. Sensitive credential fields are excluded from metadata.</span>
      </div>

      {error && <div className="alert error" role="alert">{error}</div>}

      <form className="admin-audit-filters" onSubmit={(event) => event.preventDefault()}>
        <label className="admin-audit-search">
          <span>Search all audit fields</span>
          <input value={filters.q} maxLength="120" onChange={(event) => updateFilter('q', event.target.value)} placeholder="Actor, action, entity, ID, or request ID"/>
        </label>
        <label>
          <span>Actor</span>
          <input value={filters.actor} maxLength="120" onChange={(event) => updateFilter('actor', event.target.value)} placeholder="Name or actor ID"/>
        </label>
        <label>
          <span>Action</span>
          <select value={filters.action} onChange={(event) => updateFilter('action', event.target.value)}>
            <option value="">All actions</option>
            {options.actions.map((action) => <option key={action} value={action}>{label(action)}</option>)}
          </select>
        </label>
        <label>
          <span>Module</span>
          <select value={filters.module} onChange={(event) => updateFilter('module', event.target.value)}>
            <option value="">All modules</option>
            {options.modules.map((module) => <option key={module} value={module}>{label(module)}</option>)}
          </select>
        </label>
        <label>
          <span>Entity type</span>
          <input value={filters.entityType} maxLength="80" onChange={(event) => updateFilter('entityType', event.target.value)} placeholder="e.g. booking"/>
        </label>
        <label>
          <span>Entity ID</span>
          <input value={filters.entityId} maxLength="80" onChange={(event) => updateFilter('entityId', event.target.value)}/>
        </label>
        <label>
          <span>Request ID</span>
          <input value={filters.requestId} maxLength="64" onChange={(event) => updateFilter('requestId', event.target.value)}/>
        </label>
        <label>
          <span>Severity</span>
          <select value={filters.severity} onChange={(event) => updateFilter('severity', event.target.value)}>
            <option value="">All severities</option>
            <option value="info">Info</option>
            <option value="warning">Warning</option>
            <option value="critical">Critical</option>
          </select>
        </label>
        <label>
          <span>Outcome</span>
          <select value={filters.outcome} onChange={(event) => updateFilter('outcome', event.target.value)}>
            <option value="">All outcomes</option>
            <option value="success">Success</option>
            <option value="failure">Failure</option>
          </select>
        </label>
        <label>
          <span>From date</span>
          <input type="date" value={filters.dateFrom} onChange={(event) => updateFilter('dateFrom', event.target.value)}/>
        </label>
        <label>
          <span>To date</span>
          <input type="date" value={filters.dateTo} onChange={(event) => updateFilter('dateTo', event.target.value)}/>
        </label>
        <label>
          <span>Sort by</span>
          <select value={sortBy} onChange={(event) => setSortBy(event.target.value)}>
            <option value="created_at">Timestamp</option>
            <option value="action">Action</option>
            <option value="actor_name">Actor</option>
            <option value="entity_type">Entity type</option>
            <option value="severity">Severity</option>
          </select>
        </label>
        <label>
          <span>Sort direction</span>
          <select value={sortDirection} onChange={(event) => setSortDirection(event.target.value)}>
            <option value="desc">Newest / descending</option>
            <option value="asc">Oldest / ascending</option>
          </select>
        </label>
        <label>
          <span>Rows per page</span>
          <select value={pagination.pageSize} onChange={(event) => setPagination((current) => ({
            ...current,
            page: 1,
            pageSize: Number(event.target.value),
          }))}>
            {[10, 20, 50, 100].map((pageSize) => <option key={pageSize} value={pageSize}>{pageSize}</option>)}
          </select>
        </label>
        <button className="button secondary admin-audit-reset" type="button" onClick={() => setFilters(emptyFilters)}>Clear filters</button>
      </form>

      <div className="admin-audit-results">
        <div className="admin-audit-results-heading">
          <h2>Audit history</h2>
          <span>{pagination.total.toLocaleString()} record{pagination.total === 1 ? '' : 's'}</span>
          <button className="button secondary" type="button" disabled={loading} onClick={() => void load(pagination.page)}>
            <RefreshCw size={15}/> Refresh
          </button>
        </div>
        {loading ? (
          <div className="admin-audit-state" role="status">Loading audit records…</div>
        ) : error && rows.length === 0 ? (
          <div className="admin-audit-state">
            <p>Audit records could not be loaded.</p>
            <button className="button secondary" type="button" onClick={() => void load(pagination.page)}>Try again</button>
          </div>
        ) : rows.length === 0 ? (
          <div className="admin-audit-state">No audit records match the selected filters.</div>
        ) : (
          <div className="admin-audit-list">
            {rows.map((row) => (
              <article className="admin-audit-card" key={row.id}>
                <div className="admin-audit-card-top">
                  <span className={`admin-audit-severity severity-${row.severity}`}>{label(row.severity)}</span>
                  <span className={`admin-audit-outcome outcome-${row.outcome}`}>{label(row.outcome)}</span>
                  <time dateTime={row.created_at}>{formatDate(row.created_at)}</time>
                </div>
                <div className="admin-audit-card-main">
                  <div>
                    <h3>{label(row.action)}</h3>
                    <p>{row.actor_name || 'Unknown actor'} <span>· Actor #{row.actor_id}</span></p>
                  </div>
                  <div className="admin-audit-resource">
                    <span>{label(row.module)}</span>
                    <strong>{label(row.entity_type)}{row.entity_id ? ` #${row.entity_id}` : ''}</strong>
                  </div>
                </div>
                <details className="admin-audit-details">
                  <summary>View metadata and request context</summary>
                  <dl>
                    <dt>Record</dt><dd>#{row.id}</dd>
                    <dt>Request ID</dt><dd>{row.request_id || 'Not recorded'}</dd>
                    <dt>IP address</dt><dd>{row.ip_address || 'Not recorded'}</dd>
                    <dt>Metadata</dt><dd><pre>{row.details ? JSON.stringify(row.details, null, 2) : 'Metadata is unavailable or invalid.'}</pre></dd>
                  </dl>
                </details>
              </article>
            ))}
          </div>
        )}
        {pageCount > 1 && (
          <div className="admin-audit-pagination">
            <span>Page {pagination.page} of {pageCount}</span>
            <div>
              <button className="button secondary" type="button" disabled={loading || pagination.page <= 1} onClick={() => void load(pagination.page - 1)}><ChevronLeft size={16}/> Previous</button>
              <button className="button secondary" type="button" disabled={loading || pagination.page >= pageCount} onClick={() => void load(pagination.page + 1)}>Next <ChevronRight size={16}/></button>
            </div>
          </div>
        )}
      </div>
    </section>
  );
}
