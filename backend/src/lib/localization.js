const supportedLanguages = new Set(['en', 'am']);

function languageFromHeader(value) {
  if (typeof value !== 'string') return undefined;
  const candidates = value.split(',').map((part, index) => {
    const [tag, ...parameters] = part.trim().split(';');
    const quality = parameters
      .map((parameter) => /^q=([0-9.]+)$/i.exec(parameter.trim()))
      .find(Boolean);
    return {
      tag,
      quality: quality ? Number(quality[1]) : 1,
      index,
    };
  }).filter((candidate) => candidate.quality > 0)
    .sort((left, right) => right.quality - left.quality || left.index - right.index);

  for (const candidate of candidates) {
    const language = candidate.tag.toLowerCase().split(/[-_]/, 1)[0];
    if (supportedLanguages.has(language)) return language;
  }
  return undefined;
}

export function normalizeLanguage(value, fallback = 'en') {
  if (typeof value !== 'string') return fallback;
  const language = value.trim().toLowerCase().split(/[-_,;]/, 1)[0];
  return supportedLanguages.has(language) ? language : fallback;
}

export function getRequestLanguage(req) {
  const preferredLanguage = req?.user?.preferred_language
    || req?.admin?.preferred_language
    || req?.platformUser?.preferred_language;
  if (preferredLanguage) return normalizeLanguage(preferredLanguage);

  const explicitLanguage = normalizeLanguage(req?.headers?.['x-language'], '');
  if (explicitLanguage) return explicitLanguage;
  return languageFromHeader(req?.headers?.['accept-language']) || req?.language || 'en';
}

export function translateMessage(value, language = 'en') {
  if (typeof value !== 'string') return value;
  const locale = normalizeLanguage(language);
  return messages[locale][value] || value;
}

export function localizeResponseBody(body, language = 'en') {
  if (!body || typeof body !== 'object' || Array.isArray(body) || normalizeLanguage(language) === 'en') return body;

  let localized = body;
  for (const key of ['error', 'message']) {
    if (typeof body[key] !== 'string') continue;
    const translated = translateMessage(body[key], language);
    if (translated !== body[key]) {
      if (localized === body) localized = { ...body };
      localized[key] = translated;
    }
  }

  if (Array.isArray(body.details)) {
    const details = body.details.map((detail) => {
      if (!detail || typeof detail !== 'object' || typeof detail.message !== 'string') return detail;
      const message = translateMessage(detail.message, language);
      return message === detail.message ? detail : { ...detail, message };
    });
    if (details.some((detail, index) => detail !== body.details[index])) {
      if (localized === body) localized = { ...body };
      localized.details = details;
    }
  }

  return localized;
}

export function localizationMiddleware(req, res, next) {
  req.language = normalizeLanguage(req.headers?.['x-language'], '')
    || languageFromHeader(req.headers?.['accept-language'])
    || 'en';
  req.t = (message) => translateMessage(message, getRequestLanguage(req));
  const sendJson = res.json.bind(res);
  res.json = (body) => sendJson(localizeResponseBody(body, getRequestLanguage(req)));
  next();
}
