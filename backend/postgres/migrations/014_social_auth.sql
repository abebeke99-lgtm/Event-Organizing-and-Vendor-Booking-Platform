CREATE TABLE IF NOT EXISTS oauth_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider VARCHAR(16) NOT NULL CHECK (provider IN ('google', 'facebook', 'apple')),
  provider_subject VARCHAR(255) NOT NULL,
  provider_email VARCHAR(254),
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (provider, provider_subject),
  UNIQUE (user_id, provider)
);
CREATE INDEX IF NOT EXISTS idx_oauth_identities_user ON oauth_identities(user_id);

CREATE TABLE IF NOT EXISTS oauth_login_states (
  state_hash CHAR(64) PRIMARY KEY,
  browser_hash CHAR(64) NOT NULL,
  provider VARCHAR(16) NOT NULL CHECK (provider IN ('google', 'facebook', 'apple')),
  intent VARCHAR(8) NOT NULL CHECK (intent IN ('login', 'link')),
  user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  nonce VARCHAR(128) NOT NULL,
  code_verifier VARCHAR(128),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK ((intent = 'link' AND user_id IS NOT NULL) OR (intent = 'login' AND user_id IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_oauth_login_states_expiry ON oauth_login_states(expires_at);
