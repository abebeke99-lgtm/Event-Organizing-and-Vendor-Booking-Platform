CREATE TABLE IF NOT EXISTS password_reset_otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  otp_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ip INET,
  user_agent VARCHAR(512)
);

CREATE INDEX IF NOT EXISTS idx_password_reset_otps_user_created
  ON password_reset_otps(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_password_reset_otps_expiry
  ON password_reset_otps(expires_at);

CREATE TABLE IF NOT EXISTS password_reset_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_password_reset_sessions_user
  ON password_reset_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_password_reset_sessions_expiry
  ON password_reset_sessions(expires_at);
