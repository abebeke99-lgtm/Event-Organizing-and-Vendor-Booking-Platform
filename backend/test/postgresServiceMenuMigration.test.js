import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { once } from 'node:events';
import express from 'express';
import test from 'node:test';
import { createPostgresMarketplaceRouter } from '../src/routes/postgresMarketplace.js';
import { loadNeonTestEnvironment } from '../src/lib/neonTestEnvironment.js';
import { splitPostgresSqlStatements } from '../src/lib/postgresMigrate.js';
import { createPostgresDatabase } from '../src/postgresDb.js';

const migrationUrl = new URL('../postgres/migrations/011_service_navigation_categories.sql', import.meta.url);
const additiveMigrationUrl = new URL('../postgres/migrations/013_seed_public_service_categories.sql', import.meta.url);
const expectedCategories = [
  'Photography',
  'Videography',
  'Catering',
  'Decoration',
  'Wedding Venues',
  'Event Halls',
  'Entertainment',
  'DJs and Music',
  'Transportation',
  'Makeup and Beauty',
  'Florists',
  'Event Planning',
  'Equipment Rental',
  'Lighting and Sound',
  'Security Services',
];

test('service navigation migration defines the requested 15 categories without deleting records', async () => {
  const sql = await readFile(migrationUrl, 'utf8');
  const seededNames = [...sql.matchAll(/\(\s*\d+\s*,\s*'([^']+)'/g)].map((match) => match[1]);

  assert.deepEqual(seededNames, expectedCategories);
  assert.match(sql, /ON CONFLICT \(name\) DO NOTHING/);
  assert.match(sql, /service_menu_order = NULL/);
  assert.doesNotMatch(sql, /\bDELETE\s+FROM\b|\bTRUNCATE\b|\bDROP\s+TABLE\b/i);
});

test('public service category seed is additive and uses the approved service taxonomy', async () => {
  const sql = await readFile(additiveMigrationUrl, 'utf8');
  const seededNames = [...sql.matchAll(/\(\s*\d+\s*,\s*'([^']+)'/g)].map((match) => match[1]);

  assert.deepEqual(seededNames, expectedCategories);
  assert.match(sql, /ON CONFLICT \(name\) DO NOTHING/);
  assert.doesNotMatch(sql, /\bDELETE\s+FROM\b|\bTRUNCATE\b|\bDROP\s+TABLE\b|service_menu_order\s*=\s*NULL/i);
});

test('Neon service navigation migration preserves existing category IDs and selects exactly 15 entries', {
  skip: process.env.RUN_NEON_INTEGRATION === 'true' ? false : 'Set RUN_NEON_INTEGRATION=true to use the isolated Neon test database.',
}, async () => {
  const environment = await loadNeonTestEnvironment();
  const database = createPostgresDatabase(environment);
  const client = await database.runtimePool.connect();
  let transactionOpen = false;
  let server;

  try {
    await client.query(`DROP TABLE IF EXISTS
      pg_temp.events, pg_temp.vendor_availability, pg_temp.vendor_media,
      pg_temp.service_packages, pg_temp.reviews, pg_temp.bookings,
      pg_temp.services, pg_temp.vendor_profiles, pg_temp.users, pg_temp.service_categories`);
    await client.query('BEGIN');
    transactionOpen = true;
    await client.query(`CREATE TEMP TABLE service_categories (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(120) NOT NULL UNIQUE,
      description VARCHAR(500),
      display_order INTEGER NOT NULL DEFAULT 0,
      service_menu_order INTEGER,
      service_menu_name VARCHAR(120),
      image BYTEA,
      image_mime VARCHAR(80),
      is_active BOOLEAN NOT NULL DEFAULT TRUE
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE users (
      id BIGINT PRIMARY KEY,
      full_name VARCHAR(180) NOT NULL DEFAULT 'Integration organizer',
      status VARCHAR(16) NOT NULL
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE vendor_profiles (
      id BIGINT PRIMARY KEY,
      user_id BIGINT NOT NULL,
      category_id BIGINT,
      business_name VARCHAR(180) NOT NULL DEFAULT 'Integration vendor',
      city VARCHAR(120),
      description TEXT,
      verification_status VARCHAR(16) NOT NULL,
      is_featured BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE services (
      id BIGINT PRIMARY KEY,
      vendor_id BIGINT NOT NULL,
      category_id BIGINT,
      title VARCHAR(180) NOT NULL DEFAULT 'Integration service',
      description TEXT,
      price NUMERIC(12, 2) NOT NULL DEFAULT 0,
      currency CHAR(3) NOT NULL DEFAULT 'ETB',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      status VARCHAR(16) NOT NULL
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE bookings (
      id BIGINT PRIMARY KEY,
      service_id BIGINT,
      vendor_id BIGINT,
      event_id BIGINT,
      status VARCHAR(24) NOT NULL,
      scheduled_date DATE
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE reviews (
      id BIGINT PRIMARY KEY,
      booking_id BIGINT NOT NULL,
      rating INTEGER NOT NULL,
      status VARCHAR(16) NOT NULL
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE service_packages (
      id BIGINT PRIMARY KEY,
      service_id BIGINT NOT NULL,
      name VARCHAR(180) NOT NULL,
      description TEXT,
      price NUMERIC(12, 2) NOT NULL DEFAULT 0,
      currency CHAR(3) NOT NULL DEFAULT 'ETB',
      included_features JSONB,
      extras JSONB,
      minimum_booking INTEGER,
      is_active BOOLEAN NOT NULL DEFAULT TRUE
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE vendor_media (
      id BIGINT PRIMARY KEY,
      vendor_id BIGINT,
      service_id BIGINT,
      media_type VARCHAR(24) NOT NULL,
      original_name VARCHAR(255) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE vendor_availability (
      vendor_id BIGINT NOT NULL,
      available_date DATE NOT NULL,
      status VARCHAR(16) NOT NULL
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(`CREATE TEMP TABLE events (
      id BIGINT PRIMARY KEY,
      organizer_id BIGINT NOT NULL,
      title VARCHAR(180) NOT NULL,
      event_type VARCHAR(80),
      description TEXT,
      notes TEXT,
      city VARCHAR(120),
      venue VARCHAR(180),
      cover_image_url TEXT,
      gallery_images JSONB,
      start_date TIMESTAMPTZ,
      end_date TIMESTAMPTZ,
      budget NUMERIC(12, 2),
      capacity INTEGER,
      status VARCHAR(24) NOT NULL,
      published_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      is_featured BOOLEAN NOT NULL DEFAULT FALSE
    ) ON COMMIT PRESERVE ROWS`);
    await client.query(
      `INSERT INTO service_categories (id, name, description, display_order, service_menu_order, service_menu_name)
       VALUES (41, 'Catering Services', 'Existing category fixture', 4, 1, 'Catering Services'),
              (42, 'Legacy Extra Menu', 'Legacy category fixture', 5, 2, 'Legacy Extra Menu')`,
    );
    await client.query("INSERT INTO users (id, status) VALUES (71, 'active')");
    await client.query("INSERT INTO vendor_profiles (id, user_id, category_id, verification_status) VALUES (72, 71, 41, 'verified')");
    await client.query("INSERT INTO services (id, vendor_id, category_id, status) VALUES (73, 72, 41, 'active')");

    const sql = await readFile(migrationUrl, 'utf8');
    for (const statement of splitPostgresSqlStatements(sql)) {
      await client.query(statement);
    }

    // Keep temporary fixtures on one Neon pooled backend session across both migration runs.
    await client.query('DROP TABLE pg_temp.service_navigation_selected, pg_temp.service_navigation_seed');
    for (const statement of splitPostgresSqlStatements(sql)) {
      await client.query(statement);
    }

    const result = await client.query(
      `SELECT id, name, service_menu_name, service_menu_order
       FROM service_categories
       WHERE service_menu_order IS NOT NULL
       ORDER BY service_menu_order`,
    );
    assert.deepEqual(result.rows.map((row) => row.service_menu_name), expectedCategories);
    assert.equal(Number(result.rows[2].id), 41);
    assert.equal(result.rows[2].name, 'Catering Services');

    const existing = await client.query(
      `SELECT id, name, service_menu_order, service_menu_name
       FROM service_categories WHERE id = 42`,
    );
    assert.deepEqual(existing.rows[0], {
      id: '42',
      name: 'Legacy Extra Menu',
      service_menu_order: null,
      service_menu_name: null,
    });

    const app = express();
    let queryQueue = Promise.resolve();
    const databaseAdapter = {
      dialect: 'postgres',
      query: (query, values) => {
        const result = queryQueue.then(() => client.query(query, values));
        queryQueue = result.then(() => undefined, () => undefined);
        return result;
      },
    };
    app.use('/api/platform', createPostgresMarketplaceRouter({ database: databaseAdapter }));
    server = app.listen(0, '127.0.0.1');
    await once(server, 'listening');
    const baseUrl = `http://127.0.0.1:${server.address().port}`;

    const response = await fetch(`${baseUrl}/api/platform/categories?scope=services`);
    assert.equal(response.status, 200);
    const payload = await response.json();
    assert.deepEqual(payload.categories.map((row) => row.name), expectedCategories);
    assert.equal(payload.categories[2].id, 41);
    assert.equal(payload.categories[2].vendorCount, 1);
    assert.equal(payload.categories[2].serviceCount, 1);
    for (const category of payload.categories) {
      const detail = await fetch(`${baseUrl}/api/platform/categories/${category.slug}`);
      assert.equal(detail.status, 200, category.name);
      const detailBody = (await detail.json()).data;
      assert.equal(detailBody.id, category.id);
      if (category.name === 'Catering') {
        assert.equal(detailBody.vendors.length, 1);
        assert.equal(detailBody.services.length, 1);
      }
    }

    const missingImage = await fetch(`${baseUrl}/api/platform/categories/308/image`);
    assert.equal(missingImage.status, 404);
  } finally {
    if (server?.listening) {
      server.close();
      await once(server, 'close');
    }
    if (transactionOpen) await client.query('ROLLBACK');
    await client.query(`DROP TABLE IF EXISTS
      pg_temp.events, pg_temp.vendor_availability, pg_temp.vendor_media,
      pg_temp.service_packages, pg_temp.reviews, pg_temp.bookings,
      pg_temp.services, pg_temp.vendor_profiles, pg_temp.users, pg_temp.service_categories`);
    client.release();
    await database.close();
  }
});
